import { chromium } from 'playwright';
const BASE = 'http://127.0.0.1:3000';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.on('pageerror', (e) => console.log('PAGEERROR', e.message.slice(0, 400)));
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') console.log('CONSOLE', m.type(), m.text().slice(0, 400)); });
page.on('request', (r) => { if (r.url().includes('/api/')) console.log('REQ', r.method(), r.url()); });
await page.goto(`${BASE}/auth/signup`, { waitUntil: 'networkidle' });
await page.fill('input[name="name"]', 'Demo Admin');
await page.fill('input[name="email"]', `dbg4-${Date.now()}@example.com`);
await page.fill('input[name="password"]', 'DemoPass123!');
await page.fill('input[name="confirmPassword"]', 'DemoPass123!');
await page.click('button:has-text("Sign up")');
await page.waitForURL('**/app/**', { timeout: 20000 }).catch(() => {});
console.log('--- now OPD ---');
await page.goto(`${BASE}/app/registers/opd`, { waitUntil: 'networkidle' }).catch(() => {});
await page.waitForTimeout(3000);
console.log('TEXT:', (await page.evaluate(() => document.body.innerText)).slice(0, 150));
await browser.close();
