import { chromium } from "playwright";
const BASE = "http://127.0.0.1:3000";
const browser = await chromium.launch();
const page = await browser.newPage();
page.on("response", (r) => {
  if (r.url().includes("/api/rpc") && r.status() >= 400)
    console.log("RPC ERR", r.status(), r.url().replace(BASE, ""));
});
await page.goto(`${BASE}/auth/signup`, { waitUntil: "networkidle" });
await page.fill('input[name="name"]', "QC2 Demo");
await page.fill('input[name="email"]', `qc2-${Date.now()}@example.com`);
await page.fill('input[name="password"]', "DemoPass123!");
await page.fill('input[name="confirmPassword"]', "DemoPass123!");
await page.click('button:has-text("Sign up")');
await page.waitForURL("**/app/**", { timeout: 20000 }).catch(() => {});
await page.goto(`${BASE}/app/lis`, { waitUntil: "networkidle" });
await page.waitForTimeout(1000);
await page.click('button:has-text("QC")');
await page.waitForTimeout(1500);
const sel = page.locator("select").first();
const val = await sel.locator("option").nth(1).getAttribute("value");
console.log("selected value:", val);
await sel.selectOption(val);
await page.waitForTimeout(500);
const btn = page.locator('button:has-text("Record QC Run")');
console.log("button disabled:", await btn.isDisabled());
await btn.click();
await page.waitForTimeout(2000);
const text = await page.evaluate(() => document.body.innerText);
console.log("QC RESULT:", text.includes("pass") ? "created" : "FAILED");
console.log(text.slice(0, 400));
await browser.close();
